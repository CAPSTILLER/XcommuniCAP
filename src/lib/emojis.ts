const segmenter =
  typeof Intl !== "undefined" && "Segmenter" in Intl
    ? new Intl.Segmenter(undefined, { granularity: "grapheme" })
    : null;

export function firstGrapheme(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) return "";
  if (segmenter) {
    const first = segmenter.segment(trimmed)[Symbol.iterator]().next().value as
      | { segment: string }
      | undefined;
    return first?.segment ?? "";
  }
  const match = trimmed.match(
    /\p{Extended_Pictographic}(?:\uFE0F|\u200D\p{Extended_Pictographic})*/u,
  );
  if (match) return match[0];
  return Array.from(trimmed)[0] ?? "";
}

export function graphemes(value: string): string[] {
  if (!value) return [];
  if (segmenter) {
    return Array.from(segmenter.segment(value), (s) => s.segment);
  }
  return Array.from(value);
}

export function limitGraphemes(value: string, max: number): string {
  return graphemes(value).slice(0, max).join("");
}

const RANDOM_POOL: readonly string[] = [
  ...new Set<string>([...POPULAR_EMOJIS, ...ALL_EMOJIS]),
];

export function randomEmojiPair(
  currentBg: string,
  currentFg: string,
): { bg: string; fg: string } {
  const pick = (avoid: ReadonlySet<string>) => {
    for (let i = 0; i < 48; i++) {
      const e = RANDOM_POOL[Math.floor(Math.random() * RANDOM_POOL.length)]!;
      if (!avoid.has(e)) return e;
    }
    return RANDOM_POOL.find((e) => !avoid.has(e)) ?? RANDOM_POOL[0]!;
  };
  const bg = pick(new Set([currentBg, currentFg]));
  const fg = pick(new Set([bg, currentBg, currentFg]));
  return { bg, fg };
}
