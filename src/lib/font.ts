export const ALLOWED_CHARS = /^[A-Z0-9!?$ ]$/;

export function sanitizeText(raw: string, max: number): string {
  return raw
    .toUpperCase()
    .split("")
    .filter((ch) => ALLOWED_CHARS.test(ch))
    .join("")
    .slice(0, max);
}
